export const LANGS = ["ar", "fr", "en"];
export const LANG_LABEL = { ar: "عربي", fr: "FR", en: "EN" };

let current = "fr";
try {
  const saved = localStorage.getItem("dzpos-mock-lang");
  if (D[saved]) current = saved;
} catch {
  /* no storage */
}

export function lang() {
  return current;
}

export function t(key) {
  return D[current][key] ?? D.en[key] ?? key;
}

export function setLang(l) {
  if (!D[l]) return;
  current = l;
  try {
    localStorage.setItem("dzpos-mock-lang", l);
  } catch {
    /* ignore */
  }
  applyDir();
}

export function applyDir() {
  const html = document.documentElement;
  html.lang = current;
  html.dir = current === "ar" ? "rtl" : "ltr";
}
